            $status_msg = "Database successfully imported! All tables created & Admin verified.";
            $status_type = "success";
        } else {
            $status_msg = "Database import completed with " . count($errors) . " notices/errors. Tables: " . count($existing_tables);
            $status_type = "warning";
        }
    }
}
