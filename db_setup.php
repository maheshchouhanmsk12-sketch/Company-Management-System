        if ($u_res && $u_res->num_rows > 0) {
            $admin_verified = true;
        }

        $import_stats = [
            'total_queries' => count($queries),
            'executed' => $executed,
            'errors' => count($errors),
            'tables_created' => count($existing_tables)
        ];

