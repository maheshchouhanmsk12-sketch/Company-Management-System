        $status_type = "danger";
    } else {
        $sql_content = file_get_contents($sql_dump_path);
        
        // Split queries safely
        $conn->query("SET FOREIGN_KEY_CHECKS = 0;");
        $conn->query("SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';");
        
        $queries = [];
        $lines = explode("\n", $sql_content);
        $temp = '';
        foreach ($lines as $line) {
            $trimmed = trim($line);
            if ($trimmed === '' || str_starts_with($trimmed, '--') || str_starts_with($trimmed, '/*') || str_starts_with($trimmed, '#')) {
                continue;
            }
            $temp .= $line . "\n";
            if (str_ends_with($trimmed, ';')) {
                $queries[] = $temp;
                $temp = '';
            }
        }
        if (!empty(trim($temp))) {
            $queries[] = $temp;
        }

        $executed = 0;
        $errors = [];
        foreach ($queries as $q) {
            $q = trim($q);
            if (!empty($q)) {
                if ($conn->query($q)) {
                    $executed++;
                } else {
                    $errors[] = $conn->error;
                }
            }
        }
        
        $conn->query("SET FOREIGN_KEY_CHECKS = 1;");
        
        // Refresh tables list
        $existing_tables = [];
        $tbl_res = @$conn->query("SHOW TABLES");
        if ($tbl_res) {
            while ($r = $tbl_res->fetch_array()) {
                $tname = $r[0];
                $cnt_res = @$conn->query("SELECT COUNT(*) FROM `{$tname}`");
                $cnt = $cnt_res ? $cnt_res->fetch_row()[0] : 0;
                $existing_tables[$tname] = $cnt;
